    /// <summary>
    /// The campaign proof (PRD_CRYSTALS 9.1, package I4): scripted players drive whole runs headless through commands
    /// only, on dev.historic with the faction game running underneath, and the test writes Docs/CAMPAIGN_PROOF.md.
    /// Generated and deterministic (built twice, compared byte for byte); every claim in it is also checked here.
    /// </summary>
    public class CampaignProofReport
    {
        public static readonly ulong[] Seeds = { 1, 2, 3, 4, 5 };
        private static readonly CultureInfo Inv = CultureInfo.InvariantCulture;
        private const string Authored = PackFiles.Authored, Skeleton = PackFiles.Skeleton;
        private static readonly Element[] All4 = { Element.Earth, Element.Fire, Element.Water, Element.Air };

        [Test]
        public void CampaignProof_WritesDocsCampaignProof_AndMeetsEveryCheck()
        {
            var failures = new List<string>();
            string a = new Builder(failures).Build();
            string b = new Builder(new List<string>()).Build();
            Assert.AreEqual(a, b, "the proof is byte-identical across two runs");
            string root = RepoRoot();
            if (root != null) File.WriteAllText(Path.Combine(root, "Docs", "CAMPAIGN_PROOF.md"), a.Replace("\r\n", "\n"), new UTF8Encoding(false));
            Assert.IsEmpty(failures, string.Join("\n", failures));
        }

        private static string RepoRoot()
        {
            foreach (var start in new[] { TestContext.CurrentContext.TestDirectory, Directory.GetCurrentDirectory() })
            {
                var d = new DirectoryInfo(start);
                while (d != null)
                {
                    if (Directory.Exists(Path.Combine(d.FullName, "Docs")) && Directory.Exists(Path.Combine(d.FullName, "Assets"))) return d.FullName;
                    d = d.Parent;
                }
            }
            return null;
        }

        internal static string T(long ticks) { if (ticks < 0) return "-"; long sec = ticks / 10; return (sec / 60) + ":" + (sec % 60).ToString("00", Inv); }
        internal static string Min(long ticks) => ticks < 0 ? "-" : (ticks / 600.0).ToString("0.0", Inv);
        internal static string Pct(int n, int of) => of == 0 ? "-" : (100.0 * n / of).ToString("0", Inv) + "%";
        private static string Id(Element e) => e.ToString().ToLowerInvariant();

        private sealed class Builder
        {
            private readonly List<string> _fail;
            private readonly StringBuilder _sb = new StringBuilder();
            private readonly List<ProofRun> _runs = new List<ProofRun>();
            private string _threshold;
            private int _claims;

            public Builder(List<string> failures) { _fail = failures; }

            private void Claim(bool ok, string what) { System.Threading.Interlocked.Increment(ref _claims); if (!ok) lock (_fail) _fail.Add(what); }
            private void L(string s = "") => _sb.Append(s).Append('\n');
            private ProofRun Keep(ProofRun r) { lock (_runs) _runs.Add(r); return r; }

            private static ProofPolicy Prompt(int delay = 0) => new ProofPolicy { Name = delay == 0 ? "prompt" : (delay / 10) + " s", Delay = delay };

            private static bool EarthRestored(ProofRun r) => r.C.Crystal(Element.Earth).Custody == Custody.Restored || r.C.Phase != CampaignPhase.Running;

            private static long FirstTick<TEv>(ProofRun r, Func<TEv, bool> f) where TEv : SimEvent
            {
                var e = r.Of<TEv>().FirstOrDefault(f);
                return e == null ? -1 : r.Since(e.Tick);
            }

            private static long Fact(ProofRun r, string fact) => FirstTick<FactLearned>(r, f => f.Fact == fact);

            private void Journal(ProofRun r, int max = 40)
            {
                var j = CampaignApi.Journal(r.S);
                L("| Time | Journal |");
                L("|---|---|");
                foreach (var e in j.Take(max)) L("| " + T(r.Since(e.Tick)) + " | " + e.Text.Replace("|", "/") + " |");
                if (j.Count > max) L("| ... | (" + (j.Count - max) + " more) |");
                L();
            }

            public string Build()
            {
                L("# Campaign proof (crystals, Slice 1 on the Historic island)");
                L();
                L("Generated by `CampaignProofReport` (`Assets/World/Tests/EditMode/Campaign/Proof/`), package I4 (`PRD_CRYSTALS` 9.1), at `sim-H1-cry-S1`. Do not edit by hand: `dotnet test DotNet` rewrites it. The test builds it twice and requires the two to be byte-identical, and every statement below is also an assertion of the test.");
                L();
                L("**How the runs are made.** Every run starts from `dev.historic` for its seed (the faction game really runs underneath: the prince is autonomous and builds alone, the Ash Clan plays, demons are on, overruns are the campaign setback) and sends `StartCampaign` with a shipped pack: `authored_v1` (Partial: the Earth route of Slice 1) or `skeleton_v1` (Complete: four trivial routes, the finale and both endings). Scripted players only send campaign commands and read `CampaignApi`; nobody casts a spell for the player's people. Duel results are injected through `ResolveEncounter` unless a section says they were played: then a real `WardDuelSession` was played on the attempt's own seed against the encounter's opponent profile by the scripted first-timer (`WardBalanceTests.FirstTimer`) or competent player of `WardOpponentTests`. Time is game time since the campaign started (m:ss; 10 ticks = 1 s). A pending duel is resolved on the next tick, as the game does with its world clock paused during the duel. Seeds: " + string.Join(", ", Seeds) + ".");
                L();
                SectionA();
                SectionB(out var thresholds);
                SectionC(thresholds);
                SectionD();
                SectionE(thresholds[Seeds[0]]);
                SectionF();
                SectionG();
                SectionH();
                SectionI();
                Weaknesses();
                L("---");
                L();
                L(_claims + " checks made by the test for this report.");
                return _sb.ToString();
            }

            // ------------------------------------------------------------ A

            private void SectionA()
            {
                L("## A. Earth, first arrival");
                L();
                L("The prompt player (answers every lead, question and \"Set it\" at once) on the authored pack. Timestamps of each step from the opening to the restoration.");
                L();
                var runs = new ProofRun[Seeds.Length];
                Parallel.For(0, Seeds.Length, i =>
                {
                    var r = Keep(ProofStarts.Start(Authored, Seeds[i], Prompt()));
                    r.Run(EarthRestored, 9000);
                    runs[i] = r;
                });
                L("| Seed | Glade known | Set out | Stone read, stair open | Underground | Marks read | Deepstone taken | Back on the surface | At the Rooted Tower | Restored | Rival's march to the quarry done at | Duels |");
                L("|---|---|---|---|---|---|---|---|---|---|---|---|");
                foreach (var r in runs)
                {
                    long taken = FirstTick<CrystalCustodyChanged>(r, x => x.Crystal == Element.Earth && x.To == Custody.Carried);
                    long surface = r.Of<PartyArrived>().Where(x => r.Since(x.Tick) > taken && !x.At.IsInterior).Select(x => r.Since(x.Tick)).DefaultIfEmpty(-1).First();
                    long tower = FirstTick<PartyArrived>(r, x => x.At.Location == "tower_earth");
                    long restored = FirstTick<CrystalRestored>(r, x => x.Crystal == Element.Earth);
                    long march = r.C.Definition.Rival.Steps[0].MarchCost;
                    L("| " + Seed(r) + " | " + T(Fact(r, "earth.glade_known")) + " | " + T(FirstTick<PartySetOut>(r, x => true)) + " | " + T(Fact(r, "earth.stair_open"))
                      + " | " + T(FirstTick<QuestEventFired>(r, x => x.EventId == "earth_underground")) + " | " + T(Fact(r, "earth.root_way_known")) + " | " + T(taken)
                      + " | " + T(surface) + " | " + T(tower) + " | " + T(restored) + " | " + T(march) + " | " + r.Duels.Count + " |");
                    Claim(r.Chain(Element.Earth).SequenceEqual(new[] { Custody.AtSite, Custody.Carried, Custody.Restored }), "A seed " + Seed(r) + ": custody AtSite, Carried, Restored");
                    Claim(r.Duels.Count == 0 && !r.Of<EncounterCommitted>().Any(), "A: no lethal duel on a first arrival");
                    Claim(restored > 0 && taken < march, "A: the party reaches the pedestal before the rival's march ends");
                    Claim(r.Of<QuestEventFired>().Any(x => x.EventId == "earth_restore"), "A: the restore event fires");
                    Claim(LedgerApi.IsPaid(r.S, PlayerIds.Human, "crystal:earth"), "A: the player's point");
                    Claim(r.Failures.Count == 0, "A seed " + Seed(r) + ": " + string.Join("; ", r.Failures));
                }
                L();
                L("Checked on every seed: custody went AtSite, Carried, Restored; no lethal duel; the Deepstone was taken before the Ash expedition's 8-minute march to the quarry ended; the restore event fired and the player was paid `crystal:earth`. The glade is known at 0:00 because Odo reads the foresters' marks on sight (the sawyer is the fallback). The journal of seed " + Seeds[0] + ":");
                L();
                Journal(runs[0]);
            }

            private static string Seed(ProofRun r) => r.S.Seed.ToString(Inv);

            // ------------------------------------------------------------ B

            private void SectionB(out Dictionary<ulong, string> thresholds)
            {
                L("## B. Earth stolen, then recovered");
                L();
                L("The reluctant player answers \"Not that way\" to every Earth lead until word comes that the Ash Clan has the Deepstone, then plays promptly. Mira follows the trail: the bare pedestal, the tally, the stair to the lower workings, Dolm at the Ash altar. The duel is won (injected `Victory`), the party leaves by the Ash cut (the second way out, opened by the victory) and restores the Deepstone.");
                L();
                var ths = new Dictionary<ulong, string>();
                var runs = new ProofRun[Seeds.Length];
                Parallel.For(0, Seeds.Length, i =>
                {
                    var pol = new ProofPolicy { Name = "reluctant", Reluctant = true, NeverFight = true };
                    var r = Keep(ProofStarts.Start(Authored, Seeds[i], pol));
                    r.Run(x => x.C.Party.Mode == PartyMode.AtThreshold && x.C.Party.EncounterId == "keeper_earth", 20000);
                    string json = SaveCodec.ToJson(r.S);
                    lock (ths) ths[Seeds[i]] = json;
                    r.Policy.NeverFight = false;
                    r.Run(EarthRestored, 9000);
                    runs[i] = r;
                });
                thresholds = ths;
                _threshold = ths[Seeds[0]];
                L("| Seed | Seized (truth) | Word reaches the party | Bare pedestal seen | Tally read | Vault known | At Dolm's threshold | Duel won | Out by the Ash cut | Restored | Ash points | Player points |");
                L("|---|---|---|---|---|---|---|---|---|---|---|---|");
                foreach (var r in runs)
                {
                    long seized = FirstTick<CrystalCustodyChanged>(r, x => x.Crystal == Element.Earth && x.To == Custody.RivalTransit);
                    long word = FirstTick<RivalReported>(r, x => x.Crystal == Element.Earth && x.Kind == RivalReportKind.Seized);
                    long empty = FirstTick<QuestEventFired>(r, x => x.EventId == "earth_empty" || x.EventId == "earth_empty_transit");
                    long th = FirstTick<EncounterThreshold>(r, x => x.EncounterId == "keeper_earth");
                    long won = FirstTick<EncounterResolved>(r, x => x.Result == DuelResult.Victory);
                    long cut = FirstTick<PartyArrived>(r, x => x.At == MarkerRef.Surface("ash_cut", "cut"));
                    long restored = FirstTick<CrystalRestored>(r, x => x.Crystal == Element.Earth);
                    L("| " + Seed(r) + " | " + T(seized) + " | " + T(word) + " | " + T(empty) + " | " + T(Fact(r, "earth.tally_read")) + " | " + T(Fact(r, "earth.vault_known"))
                      + " | " + T(th) + " | " + T(won) + " | " + T(cut) + " | " + T(restored) + " | " + LedgerApi.Points(r.S, PlayerIds.Rival) + " | " + LedgerApi.Points(r.S, PlayerIds.Human) + " |");
                    Claim(r.Chain(Element.Earth).SequenceEqual(new[] { Custody.AtSite, Custody.RivalTransit, Custody.AtRivalAltar, Custody.Carried, Custody.Restored }), "B seed " + Seed(r) + ": the stolen chain " + string.Join(",", r.Chain(Element.Earth)));
                    Claim(empty > 0 && th > empty && won > th && cut > won && restored > cut, "B seed " + Seed(r) + ": the trail in order");
                    Claim(r.C.Knows("earth.ash_cut_open") && CampaignApi.IsOpen(r.S, "ash_cut_way"), "B: the Ash cut is open after the victory");
                    Claim(LedgerApi.IsPaid(r.S, PlayerIds.Rival, "crystal:earth") && LedgerApi.IsPaid(r.S, PlayerIds.Human, "crystal:earth"), "B: both points paid once");
                    Claim(r.Duels.Count == 1 && CampaignApi.Companions(r.S).All(k => k.Alive), "B: one duel, nobody lost");
                    Claim(r.Failures.Count == 0, "B seed " + Seed(r) + ": " + string.Join("; ", r.Failures));
                }
                L();
                L("Checked on every seed: custody went AtSite, RivalTransit, AtRivalAltar, Carried, Restored; the steps came in this order; the Ash cut opened; the Ash Clan was paid `crystal:earth` when the Deepstone reached its altar and the player when it was restored. The journal of seed " + Seeds[0] + ":");
                L();
                Journal(runs[0], 60);

                // Real duels against keeper_earth on the campaign's own attempt seeds.
                L("**Real duels against Dolm (`keeper_earth`).** At Dolm's threshold of each seed the duel was committed and staged again 199 times (`RestartAttempt`, each a new seed from the campaign's random stream), and every one of those 200 attempt seeds was played as a real Ward duel by the scripted first-timer and by the competent player:");
                L();
                L("| Seed | First-timer win | lose | draw | Competent win | lose | draw | The first attempt, first-timer |");
                L("|---|---|---|---|---|---|---|---|");
                int fw = 0, fl = 0, fn = 0, cw = 0, cl = 0, cn = 0;
                var rows = new string[Seeds.Length];
                Parallel.For(0, Seeds.Length, i =>
                {
                    var r = new ProofRun(SaveCodec.Load(ths[Seeds[i]], out _), Prompt());
                    r.Do(new CommitEncounter { EncounterId = "keeper_earth" });
                    var seeds = new List<ulong> { r.C.Attempt.Seed };
                    int id = r.C.Attempt.Id;
                    for (int k = 1; k < 200; k++) { r.Do(new RestartAttempt { AttemptId = id }); seeds.Add(r.C.Attempt.Seed); }
                    int[] f = new int[3], c = new int[3];
                    foreach (var sd in seeds)
                    {
                        Count(f, ProofRun.PlayWard("keeper_earth", sd, WardOpponentTests.FirstTimer));
                        Count(c, ProofRun.PlayWard("keeper_earth", sd, WardOpponentTests.Competent));
                    }
                    var first = ProofRun.PlayWard("keeper_earth", seeds[0], WardOpponentTests.FirstTimer);
                    lock (rows) { fw += f[0]; fl += f[1]; fn += f[2]; cw += c[0]; cl += c[1]; cn += c[2]; }
                    rows[i] = "| " + Seeds[i] + " | " + Pct(f[0], 200) + " | " + Pct(f[1], 200) + " | " + Pct(f[2], 200) + " | " + Pct(c[0], 200) + " | " + Pct(c[1], 200) + " | " + Pct(c[2], 200) + " | " + first + " |";
                    Claim(seeds.Distinct().Count() == 200, "B: 200 distinct attempt seeds");
                });
                foreach (var row in rows) L(row);
                int n = 200 * Seeds.Length;
                L("| all | " + Pct(fw, n) + " | " + Pct(fl, n) + " | " + Pct(fn, n) + " | " + Pct(cw, n) + " | " + Pct(cl, n) + " | " + Pct(cn, n) + " | |");
                L();
                double fr = (double)fw / n;
                Claim(fr >= 0.60 && fr <= 0.80, "B: the first-timer wins about 7 in 10 against Dolm on campaign seeds (" + fr + ")");
                Claim(cw > fw, "B: the competent player wins more often than the first-timer");
                L("In context the first-timer wins " + Pct(fw, n) + " of keeper duels on the campaign's own attempt seeds (the owner's target: about 7 in 10; I3 measured 65 to 75% on its own seeds), the competent player " + Pct(cw, n) + ". Section H plays these duels for real inside whole runs.");
                L();
            }

            private static void Count(int[] a, DuelResult r) { if (r == DuelResult.Victory) a[0]++; else if (r == DuelResult.Defeat || r == DuelResult.Surrender) a[1]++; else a[2]++; }

            // ------------------------------------------------------------ C

            private void SectionC(Dictionary<ulong, string> ths)
            {
                L("## C. A loss that kills the first volunteer, then a win");
                L();
                L("From Dolm's threshold of section B: the first duel is lost (injected `Defeat`), the second won. Run twice from the same save: once unbroken, once saved and loaded right before and right after each resolution, with every `ResolveEncounter` sent a second time after its load.");
                L();
                L("| Seed | Volunteer | Fell | Party placed at | Rival charge | Rival (phase step/progress): before, after the loss | Retry volunteer | Won | Restored | Duplicate resolutions refused | Final state equal, reloaded vs unbroken |");
                L("|---|---|---|---|---|---|---|---|---|---|---|");
                foreach (var seed in Seeds.Take(3))
                {
                    var pol = Prompt();
                    pol.Inject.Add(DuelResult.Defeat);
                    var u = Keep(new ProofRun(SaveCodec.Load(ths[seed], out _), pol.Clone()));
                    string before = "";
                    u.Run(x => { if (x.C.Attempt != null && x.Duels.Count == 0) before = x.C.Rival.Phase + " " + x.C.Rival.Step + "/" + x.C.Rival.StepProgress; return EarthRestored(x); }, 9000);
                    var lostAt = u.Of<EncounterResolved>().First();
                    var fell = u.Of<CompanionFell>().ToList();
                    var retreat = u.Of<PartyRetreated>().First(x => x.Why == "defeat");
                    var charge = u.Of<RivalAdvanced>().First(x => x.Why == RivalCharges.Defeat);
                    long end = u.S.Tick;

                    // Reloaded path.
                    var l = Keep(new ProofRun(SaveCodec.Load(ths[seed], out _), pol.Clone()));
                    int refused = 0, resolutions = 0;
                    string after = "";
                    while (l.S.Tick < end)
                    {
                        if (l.C.Attempt != null) l = ProofStarts.Reload(l);
                        int duels = l.Duels.Count;
                        l.Tick();
                        if (l.Duels.Count > duels)
                        {
                            resolutions++;
                            var last = l.Duels[l.Duels.Count - 1];
                            if (resolutions == 1) after = l.C.Rival.Phase + " " + l.C.Rival.Step + "/" + l.C.Rival.StepProgress;
                            l = ProofStarts.Reload(l);
                            var again = l.Sim.Submit(new ResolveEncounter { AttemptId = last.AttemptId, Result = last.Result });
                            if (!again.Ok && again.Reason == "already_resolved") refused++;
                        }
                    }
                    bool same = SaveCodec.StateJson(u.S) == SaveCodec.StateJson(l.S);
                    int fellCount = l.C.Companions.Count(k => !k.Alive);
                    L("| " + seed + " | " + u.Duels[0].Volunteer + " | " + string.Join(", ", fell.Select(f => f.CompanionId)) + " | " + CampaignTokens.PlaceName(u.C.Definition, retreat.To)
                      + " | +" + charge.Amount + " | " + before + ", " + after + " | " + (u.Duels.Count > 1 ? u.Duels[1].Volunteer : "-") + " | " + (u.Duels.Count > 1 ? T(u.Since(u.Duels[1].Tick)) : "-") + " | " + T(FirstTick<CrystalRestored>(u, x => true))
                      + " | " + refused + " of " + resolutions + " | " + (same ? "yes" : "NO") + " |");
                    Claim(u.Duels.Count == 2 && u.Duels[0].Volunteer == "garrick" && u.Duels[1].Volunteer == "ivo", "C: Garrick volunteers, then Ivo");
                    Claim(fell.Count == 1 && fell[0].CompanionId == "garrick", "C: Garrick falls, once");
                    Claim(retreat.To == new MarkerRef("glade", "quarry_upper", "safe") && retreat.Tick == lostAt.Tick, "C: placed at the survey gallery in the loss's tick");
                    Claim(charge.Amount == 900 && charge.Tick == lostAt.Tick, "C: rival +900 at the loss");
                    Claim(u.Chain(Element.Earth).Last() == Custody.Restored, "C: then won and restored");
                    Claim(refused == 2 && resolutions == 2, "C: both duplicate resolutions refused with already_resolved");
                    Claim(same, "C seed " + seed + ": the reloaded run ends in the same state as the unbroken one");
                    Claim(fellCount == 1 && LedgerApi.Points(l.S, PlayerIds.Human) == 1 && l.Of<PointsAwarded>().Count(x => x.Faction == PlayerIds.Human) == 1, "C: one casualty, one point, after all the loads");
                    Claim(u.Failures.Count == 0 && l.Failures.Count == 0, "C: " + string.Join("; ", u.Failures.Concat(l.Failures)));
                }
                L();
                L("Checked: Garrick (volunteer order 1) holds the way out and dies, once; the party is placed in the survey gallery in the same tick; the Ash expedition is charged +900 there and then (its plan step and progress before and after are shown: by then the Deepstone is on the altar and the expedition is marching on the next crystal, so the loss moves it 900 ticks further along its plan); Ivo is the next volunteer; the second attempt wins and the Deepstone is restored. On the reloaded path the save was written and loaded with a duel pending and again after each resolution; each resolution was sent a second time after its load and refused with `already_resolved`; the final state (campaign and faction game) equals the unbroken run's byte for byte, with one casualty and one point.");
                L();
            }

            // ------------------------------------------------------------ D

            private void SectionD()
            {
                L("## D. Six losses, a win with nobody left, and the seventh loss");
                L();
                L("Skeleton pack, prompt player, the first six lethal duels lost (injected), then won. The skeleton's only lethal duel for a prompt player is the finale (nothing is stolen), so all six fall at the last tower; each loss retreats to that tower's safe point and the finale stays open.");
                L();
                var pol = Prompt();
                for (int i = 0; i < 6; i++) pol.Inject.Add(DuelResult.Defeat);
                var r = Keep(ProofStarts.Start(Skeleton, Seeds[0], pol));
                string six = null;
                r.Run(x =>
                {
                    if (six == null && x.C.Companions.All(k => !k.Alive) && x.C.Party.Mode == PartyMode.AtThreshold) six = SaveCodec.ToJson(x.S);
                    return x.C.Phase != CampaignPhase.Running;
                }, 30000);
                var rec = CampaignApi.Record(r.S);
                L("| # | Time | Encounter | Volunteer | Result | Place |");
                L("|---|---|---|---|---|---|");
                for (int i = 0; i < r.Duels.Count; i++)
                {
                    var dd = r.Duels[i];
                    string place = i < rec.Fallen.Count ? rec.Fallen[i].Place : CampaignTokens.PlaceName(r.C.Definition, r.C.Party.At);
                    L("| " + (i + 1) + " | " + T(r.Since(dd.Tick)) + " | " + dd.Encounter + " | " + (dd.Volunteer.Length == 0 ? "nobody" : dd.Volunteer) + " | " + dd.Result + " | " + place + " |");
                }
                L();
                var order = r.C.Definition.Companions.OrderBy(k => k.VolunteerOrder).Select(k => k.Id).ToArray();
                Claim(rec.Fallen.Select(f => f.Id).SequenceEqual(order), "D: six named deaths in volunteer order");
                Claim(r.C.Phase == CampaignPhase.Won && r.C.EndingId == "restored" && rec.Survivors.Count == 0, "D: the restored ending with zero companions");
                Claim(r.Duels.Count == 7 && r.Duels[6].Volunteer == "" && r.Duels[6].Result == DuelResult.Victory, "D: the seventh duel is fought with nobody to hold the way out, and won");
                Claim(r.Failures.Count == 0, "D: " + string.Join("; ", r.Failures));
                L("Ending: `" + r.C.EndingId + "` (" + r.C.Phase + "), survivors: " + rec.Survivors.Count + ", the fallen in order: " + string.Join(", ", rec.Fallen.Select(f => f.Name + " (" + f.Place + ", " + f.Cause + ")")) + ". The ending's variant for no survivors is `" + r.C.Definition.Endings.First(e => e.Outcome == CampaignPhase.Won).Variants.First(v => v.Survivors == SurvivorBand.None).Lines[0] + "`.");
                L();
                // The seventh lethal loss.
                Claim(six != null, "D: the state with six fallen at the finale's threshold was saved");
                var pol7 = Prompt();
                pol7.Inject.Add(DuelResult.Defeat);
                var r7 = Keep(new ProofRun(SaveCodec.Load(six, out _), pol7));
                r7.Run(x => x.C.Phase != CampaignPhase.Running, 3000);
                var ended = r7.Of<CampaignEnded>().SingleOrDefault();
                Claim(ended != null && !ended.Won && ended.EndingId == "unwoven", "D: the seventh lethal loss ends the run with the terminal ending");
                Claim(r7.Sim.Submit(new ConfirmRestore { Crystal = Element.Air }).Reason == "campaign_over", "D: after it, commands are refused with campaign_over");
