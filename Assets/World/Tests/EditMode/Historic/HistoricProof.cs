using System.Collections.Generic;
using System.IO;
using System.Linq;
using System.Text;
using NUnit.Framework;
using World.Sim.Historic;

namespace World.Sim.Tests
{
    /// <summary>
    /// G4-2 proof (PRD_GODBOARD 11.3, HI-3, HI-6): after AI-only god board games end with a winner, 60 minutes (36000 ticks)
    /// of AI-only Historic. Every people should raise its three castle stages (G4-1 done-when), and no people may go more than
    /// 5 minutes (3000 ticks) without wood reaching its store (G4-2 done-when). Writes Docs/progress/G4-2-proof.md.
    /// </summary>
    public class HistoricProof
    {
        public const ulong FirstSeed = 3000;
        public const int Games = 8;
        public const int HistoricTicks = 36000;
        public const long WoodGapLimit = 3000;

        public sealed class PeopleResult
        {
            public int People;
            public int Stages;
            public long[] StageMinutesX10 = new long[3];
            public long WoodGap;
            public long WoodEmpty;
            public int Felled;
            public int Planted;
            public int Woodcutters;
            public int Foresters;
            public int QuarriesBuilt;
            public int QuarriesExhausted;
            public int Buildings;
            public int[] Stock;
        }

        public sealed class GameResult
        {
            public ulong Seed;
            public int Winner;
            public long SwitchTick;
            public long Ms;
            public List<PeopleResult> Peoples = new List<PeopleResult>();
            public int MatureAtSwitch, MatureAtEnd, GrowingAtEnd, StumpsAtEnd;
            public int RockAtSwitch, RockAtEnd;
            public bool Balanced;
        }

        public static GameResult Run(ulong seed, out ulong usedSeed)
        {
            var (sim, _, k) = HistoricTests.PlayToHistoric(seed);
            usedSeed = k;
            var s = sim.State;
            var g = new GameResult { Seed = k, Winner = s.Historic.Winner, SwitchTick = s.Historic.StartTick };
            g.MatureAtSwitch = HistoricApi.Trees(s, TreeStage.Mature);
            g.RockAtSwitch = s.Historic.Hexes.Sum(r => r.Rock);
            var sw = System.Diagnostics.Stopwatch.StartNew();
            for (int i = 0; i < HistoricTicks; i++)
            {
                sim.Step();
                sim.DrainEvents();
            }
            g.Ms = sw.ElapsedMilliseconds;
            var h = s.Historic;
            foreach (var hp in h.Peoples)
            {
                var r = new PeopleResult
                {
                    People = hp.Id, Stages = hp.Castle.StagesDone, WoodGap = HistoricApi.LongestWoodGap(s, hp.Id),
                    WoodEmpty = HistoricApi.LongestWoodEmpty(s, hp.Id), Felled = hp.TreesFelled, Planted = hp.TreesPlanted,
                    Woodcutters = HistoricPlanner.CountOf(h, hp.Id, HistoricKind.Woodcutter),
                    Foresters = HistoricPlanner.CountOf(h, hp.Id, HistoricKind.Forester),
                    QuarriesBuilt = h.Buildings.Count(b => b.People == hp.Id && b.Kind == HistoricKind.Quarry),
                    QuarriesExhausted = h.Buildings.Count(b => b.People == hp.Id && b.State == HistoricBuildingState.Exhausted),
                    Buildings = h.Buildings.Count(b => b.People == hp.Id),
                    Stock = (int[])hp.Stock.Clone(),
                };
                for (int st = 0; st < 3; st++)
                    r.StageMinutesX10[st] = hp.Castle.RaisedTick[st] < 0 ? -1 : (hp.Castle.RaisedTick[st] - h.StartTick) / 60;
                g.Peoples.Add(r);
            }
            g.MatureAtEnd = HistoricApi.Trees(s, TreeStage.Mature);
            g.GrowingAtEnd = HistoricApi.Trees(s, TreeStage.Sapling) + HistoricApi.Trees(s, TreeStage.Young);
            g.StumpsAtEnd = HistoricApi.Trees(s, TreeStage.Stump);
            g.RockAtEnd = h.Hexes.Sum(x => x.Rock);
            g.Balanced = HistoricApi.Imbalance(s).All(x => x == 0);
            return g;
        }

        private static string Min(long ticks) => (ticks / 600.0).ToString("0.0", System.Globalization.CultureInfo.InvariantCulture);
        private static string M10(long x10) => x10 < 0 ? "-" : (x10 / 10.0).ToString("0.0", System.Globalization.CultureInfo.InvariantCulture);

        public static string Report(List<GameResult> games)
        {
            var sb = new StringBuilder();
            sb.AppendLine("# G4-2 proof: 60 minutes of AI-only Historic after a god board game");
            sb.AppendLine();
            sb.AppendLine("Generated by `HistoricProof` (EditMode; `dotnet test DotNet --filter \"FullyQualifiedName~HistoricProof\"`). " +
                          "Each game: an AI-only god board game (`GameSetup.GodBoard`, table seat -1) from seed " + FirstSeed +
                          " up, skipping seeds where the island falls, played to `AgeEnded`; the island steps into Historic in that tick; then " +
                          HistoricTicks + " ticks (60 minutes) with every people run by the Historic planner. Times are minutes after the switch.");
            sb.AppendLine();
            var all = games.SelectMany(g => g.Peoples).ToList();
            sb.AppendLine("| Measure | Target | Value |");
            sb.AppendLine("|---|---|---|");
            sb.AppendLine("| Peoples with all three castle stages (HI-3) | all | " + all.Count(p => p.Stages == 3) + " of " + all.Count + " |");
            sb.AppendLine("| Castle stages raised (wood / brick / stone) | | " + all.Count(p => p.Stages >= 1) + " / " + all.Count(p => p.Stages >= 2) + " / " + all.Count(p => p.Stages >= 3) + " |");
            var stone = all.Where(p => p.StageMinutesX10[2] >= 0).Select(p => p.StageMinutesX10[2]).OrderBy(x => x).ToList();
            if (stone.Count > 0)
                sb.AppendLine("| Minutes to the stone stage (min / median / max) | | " + M10(stone.First()) + " / " + M10(stone[stone.Count / 2]) + " / " + M10(stone.Last()) + " |");
            sb.AppendLine("| Longest stretch without wood reaching the store (HI-6), worst people | at most 5.0 min | " + Min(all.Max(p => p.WoodGap)) + " min |");
            sb.AppendLine("| Longest stretch with an empty wood store, worst people | (reported) | " + Min(all.Max(p => p.WoodEmpty)) + " min |");
            sb.AppendLine("| Peoples with at least as many foresters as woodcutters at the end | all | " + all.Count(p => p.Foresters >= p.Woodcutters) + " of " + all.Count + " |");
            sb.AppendLine("| Ware books balanced at the end | all games | " + games.Count(g => g.Balanced) + " of " + games.Count + " |");
            sb.AppendLine("| Sim time for 60 minutes of Historic (whole sim, Debug build) | | " + games.Min(g => g.Ms) + "-" + games.Max(g => g.Ms) + " ms |");
            sb.AppendLine();
            sb.AppendLine("## Games");
            sb.AppendLine();
            sb.AppendLine("| Seed | Winner | Switch tick | Grown trees at switch / end | Growing / stumps at end | Rock at switch / end |");
            sb.AppendLine("|---|---|---|---|---|---|");
            foreach (var g in games)
                sb.AppendLine("| " + g.Seed + " | " + g.Winner + " | " + g.SwitchTick + " | " + g.MatureAtSwitch + " / " + g.MatureAtEnd + " | " + g.GrowingAtEnd + " / " + g.StumpsAtEnd + " | " + g.RockAtSwitch + " / " + g.RockAtEnd + " |");
            sb.AppendLine();
            sb.AppendLine("## Peoples");
            sb.AppendLine();
            sb.AppendLine("| Seed | People | Stages | Wood / brick / stone at (min) | Wood gap (min) | Store empty (min) | Felled / planted | Woodcutters / foresters | Quarries built / exhausted | Buildings | Store at end (wood, clay, grain, sheep, stone, bricks) |");
            sb.AppendLine("|---|---|---|---|---|---|---|---|---|---|---|");
            foreach (var g in games)
                foreach (var p in g.Peoples)
                    sb.AppendLine("| " + g.Seed + " | " + p.People + " | " + p.Stages + " | " + string.Join(" / ", p.StageMinutesX10.Select(M10)) + " | " + Min(p.WoodGap) + " | " + Min(p.WoodEmpty)
                                  + " | " + p.Felled + " / " + p.Planted + " | " + p.Woodcutters + " / " + p.Foresters + " | " + p.QuarriesBuilt + " / " + p.QuarriesExhausted
                                  + " | " + p.Buildings + " | " + string.Join(", ", new[] { 0, 1, 2, 3, 4, 6 }.Select(w => p.Stock[w])) + " |");
            return sb.ToString();
        }

        [Test]
        public void SixtyMinutesOfAiOnlyHistoric_CastlesRise_AndNoPeopleIsOutOfWood()
        {
            var games = new List<GameResult>();
            ulong seed = FirstSeed;
            while (games.Count < Games)
            {
                games.Add(Run(seed, out var used));
                seed = used + 1;
            }
            string report = Report(games);
            TestContext.Out.WriteLine(report);
            string root = RepoRoot();
            if (root != null)
                File.WriteAllText(Path.Combine(root, "Docs", "progress", "G4-2-proof.md"), report.Replace("\r\n", "\n"), new UTF8Encoding(false));
            foreach (var g in games)
            {
                Assert.IsTrue(g.Balanced, "ware books, seed " + g.Seed);
                foreach (var p in g.Peoples)
                {
                    Assert.AreEqual(3, p.Stages, "castle stages, seed " + g.Seed + " people " + p.People);
                    Assert.LessOrEqual(p.WoodGap, WoodGapLimit, "HI-6 wood gap, seed " + g.Seed + " people " + p.People);
                }
            }
        }

        private static string RepoRoot()
        {
            foreach (var start in new[] { TestContext.CurrentContext.TestDirectory, Directory.GetCurrentDirectory() })
                for (var d = new DirectoryInfo(start); d != null; d = d.Parent)
                    if (Directory.Exists(Path.Combine(d.FullName, "Docs", "progress")) && Directory.Exists(Path.Combine(d.FullName, "Assets"))) return d.FullName;
            return null;
        }
    }
}
