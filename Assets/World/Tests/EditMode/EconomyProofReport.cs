        private static void Conservation(StringBuilder md)
        {
            md.Append("## D. Conservation\n\n");
            md.Append("Long games driven by random valid and invalid commands of every kind (roads, buildings, cancels, switches, priorities, rounds, cities, trades, sales, purchases, hero moves, ")
              .Append("draft picks, cards, wonder stages, soldiers, squad orders) plus random gifts of wares and coin. Every tick all invariants were checked. At the end every ware was counted: ")
              .Append("what is in stores and on carriers must equal starting stock + harvested + made by recipes + added - used, and every used unit must belong to a named sink.\n\n");
            md.Append("| Seed | Ticks | Commands accepted / refused | Units harvested | Units made | Units used | Balance error | Sink error | Recipe error |\n|---|---|---|---|---|---|---|---|---|\n");
            int totalErrors = 0;
            foreach (var (seed, cmd) in new[] { (4242UL, 777UL), (EconomyTestKit.DefaultSeed, 1UL), (99UL, 2UL), (123456UL, 3UL) })
            {
                var run = StrategyConservationTests.Run(seed, cmd, 20000);
                var s = run.State;
                var l = s.Economy.Ledger;
                var inWorld = EconomyApi.WaresInWorld(s);
                int balance = 0, sink = 0, recipe = 0;
                var spent = StrategyApi.WaresSpent(s);
                for (int w = 0; w < Wares.Count; w++)
                {
                    balance += Math.Abs(inWorld[w] - (l.Starting[w] + l.Harvested[w] + l.Produced[w] + l.Added[w] - l.Consumed[w]));
                    int recipeIn = 0;
                    for (int t = 0; t < BuildingDefs.Count; t++) recipeIn += l.RecipeIn[t][w];
                    sink += Math.Abs(l.Consumed[w] - (recipeIn + l.Construction[w] + l.Roads[w] + l.External[w]));
                    sink += Math.Abs(l.External[w] - (spent[w] + s.Military.ConsumedForUnits[w]));
                }
                // Recipes: inputs used = started cycles x inputs; outputs = finished cycles x outputs (+ card bonus).
                foreach (var d in s.Economy.Tuning.Buildings)
                {
                    int ti = (int)d.Type;
                    int running = s.Economy.Buildings.Count(b => b.Type == d.Type && b.State == BuildingState.Active && b.WorkProgress > 0);
                    if (d.Kind == BuildingKind.Producer)
                        for (int w = 0; w < Wares.Count; w++) recipe += Math.Abs(l.RecipeIn[ti][w] - (l.Cycles[ti] + running) * d.Inputs[w]);
                    if (d.Kind == BuildingKind.Producer && s.Economy.Bonus.ExtraOutput[ti] == 0)
                        for (int w = 0; w < Wares.Count; w++) recipe += Math.Abs(l.RecipeOut[ti][w] - l.Cycles[ti] * d.Outputs[w]);
                    if (d.Kind == BuildingKind.Harvester)
                        for (int w = 0; w < Wares.Count; w++) recipe += Math.Abs(l.RecipeOut[ti][w] - l.Cycles[ti] * (d.Outputs[w] > 0 ? Math.Max(1, d.Outputs[w]) : 0));
                    if (d.Kind == BuildingKind.Harvester && d.CyclesPerInput > 0)
                    {
                        int credit = s.Economy.Buildings.Where(b => b.Type == d.Type).Sum(b => b.InputCredit);
                        for (int w = 0; w < Wares.Count; w++)
                            if (d.Inputs[w] > 0) recipe += Math.Abs(l.RecipeIn[ti][w] / d.Inputs[w] * d.CyclesPerInput - (l.Cycles[ti] + running + credit));
                    }
                    if (d.Kind == BuildingKind.PowerPlant)
                        for (int w = 0; w < Wares.Count; w++) recipe += Math.Abs(l.RecipeIn[ti][w] - l.Cycles[ti] * d.Inputs[w]);
                }
                totalErrors += balance + sink + recipe;
                RandomBreaches.Add(s.Strategy.Breaches);
                md.Append("| ").Append(seed).Append(" | ").Append(run.Ticks).Append(" | ").Append(run.Accepted).Append(" / ").Append(run.Refused).Append(" | ")
                  .Append(l.Harvested.Sum()).Append(" | ").Append(l.Produced.Sum()).Append(" | ").Append(l.Consumed.Sum()).Append(" | ")
                  .Append(balance).Append(" | ").Append(sink).Append(" | ").Append(recipe).Append(" |\n");
                Assert.AreEqual(0, balance, "seed " + seed + " ware balance");
                Assert.AreEqual(0, sink, "seed " + seed + " sinks");
                Assert.AreEqual(0, recipe, "seed " + seed + " recipes");
            }
            md.Append("\nTotal error over all seeds and wares: ").Append(totalErrors).Append(" units. Sinks counted: recipe inputs, the miners' rations, power plant coal, construction, roads, ")
              .Append("and spending by cities, cards, the wonder, the market and soldiers (which must equal what those systems report spending). Recipes: inputs used match started cycles, outputs match finished cycles.\n\n");
            Assert.AreEqual(0, totalErrors);
        }

