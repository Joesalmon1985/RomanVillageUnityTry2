        private static void WareAudit(StringBuilder md)
        {
            var s = WorldSimFactory.CreateNew(EconomyTestKit.DefaultSeed).State;
            var t = s.Economy.Tuning;
            var st = s.Strategy.Tuning;
            var mt = s.Military.Tuning;
            var played = GameRuns.Seeds.SelectMany(seed => new[] { GameRuns.Get(seed, "competent"), GameRuns.Get(seed, "full") }).ToList();
            var full = GameRuns.Get(EconomyTestKit.DefaultSeed, "full");

            md.Append("## A. Ware audit\n\n");
            md.Append("For every ware: what makes it, what uses it, and how much of it was really made and used in one full game (default seed ")
              .Append(EconomyTestKit.DefaultSeed).Append(", the scripted player that also fights). \"Market\" (trade 4:1, sell for coin) can take any ware and is not counted as a use.\n\n");
            md.Append("| Ware | Made by | Used by (recipes) | Spent on | Made in the game | Used in the game |\n|---|---|---|---|---|---|\n");
            foreach (var w in Wares.All)
            {
                var makers = new List<string>();
                foreach (var d in t.Buildings)
                {
                    if (d.Outputs[(int)w] <= 0 || (d.Kind != BuildingKind.Producer && d.Kind != BuildingKind.Harvester)) continue;
                    makers.Add(d.Name + " (" + EconomyApi.RecipeText(s, d.Type) + ")");
                }
                var users = new List<string>();
                foreach (var d in t.Buildings)
                {
                    if (d.Inputs[(int)w] <= 0) continue;
                    string what = d.Kind == BuildingKind.PowerPlant ? "fuel" : d.Kind == BuildingKind.Harvester ? "miners' food" : "recipe";
                    users.Add(d.Name + " (" + what + ")");
                }
                var sinks = Sinks(s, w);
                int made = full.Ledger.Harvested[(int)w] + full.Ledger.Produced[(int)w];
                int used = full.Ledger.Consumed[(int)w];
                md.Append("| ").Append(Wares.Title(w)).Append(" | ").Append(string.Join("; ", makers)).Append(" | ")
                  .Append(users.Count == 0 ? "-" : string.Join("; ", users)).Append(" | ")
                  .Append(sinks.Count == 0 ? "-" : string.Join("; ", sinks)).Append(" | ").Append(made).Append(" | ").Append(used).Append(" |\n");
                Assert.IsNotEmpty(makers, "every ware has a producer: " + w);
                Assert.IsTrue(users.Count + sinks.Count > 0, "every ware has a use or sink: " + w);
                Assert.Greater(played.Sum(g => g.Ledger.Harvested[(int)w] + g.Ledger.Produced[(int)w]), 0, w + " is made in the scripted games");
                Assert.Greater(played.Sum(g => g.Ledger.Consumed[(int)w]), 0, w + " is used in the scripted games");
            }
            md.Append("\nEvery ware has at least one maker and at least one use, and every ware was both made and used in the scripted games (checked).\n\n");

            // Buildings: reachable (its inputs are made, its terrain exists) and purposeful (its output is used, or it has a role).
            md.Append("| Building | Size and cost | Needs | Makes / purpose | Built in the scripted games |\n|---|---|---|---|---|\n");
            var map = s.Board;
            foreach (var d in t.Buildings.Where(d => d.Placeable))
            {
                var v = EconomyApi.DescribeType(s, d.Type);
                foreach (var w in Wares.All)
                    if (d.Inputs[(int)w] > 0) Assert.IsNotEmpty(EconomyApi.ProducersOf(s, w), d.Name + " input " + w + " is made somewhere");
                if (d.NeedsTerrain) Assert.IsTrue(map.HexTerrain.Contains(d.Terrain), d.Name + " terrain exists on the map");
                bool purpose = d.Kind == BuildingKind.Forester || d.Kind == BuildingKind.PowerPlant || d.Type == BuildingType.Barracks
                               || d.Type == BuildingType.Market || d.Type == BuildingType.WonderSite;
                foreach (var w in Wares.All)
                    if (d.Outputs[(int)w] > 0 && (EconomyApi.ConsumersOf(s, w).Count > 0 || Sinks(s, w).Count > 0)) purpose = true;
                Assert.IsTrue(purpose, d.Name + " has a purpose");
                int games = played.Count(g => g.Buildings.Any(b => b.type == d.Type));
                Assert.Greater(games, 0, d.Name + " is built in at least one scripted game");
                md.Append("| ").Append(d.Name).Append(" | ").Append(d.Size).Append(": ").Append(v.CostText).Append(" | ")
                  .Append(v.NeedsText.Replace("Needs: ", "")).Append(" | ").Append(v.MakesText.Replace("Makes: ", "")).Append(" ").Append(d.Purpose)
                  .Append(" | ").Append(games).Append(" of ").Append(played.Count).Append(" |\n");
            }
            md.Append("\nEvery building's inputs are made by another building, its terrain is on the map, its output is used (or it has a role: forester, power, soldiers, market rate, wonder), and the scripted players built every one of them at least once (checked).\n\n");
            md.Append("| Terrain | Raw ware | Harvester |\n|---|---|---|\n");
            foreach (var w in Wares.Raw)
            {
                var terr = TerrainInfo.TerrainOf(w);
                var h = t.Buildings.Single(d => d.Kind == BuildingKind.Harvester && d.Terrain == terr);
                md.Append("| ").Append(terr).Append(" | ").Append(Wares.Title(w)).Append(" | ").Append(h.Name).Append(" |\n");
            }
            md.Append("\nEvery resource terrain has exactly one harvester (checked). Meadow yields nothing.\n\n");
        }

        /// <summary>Non-recipe uses of a ware: construction, roads, cities, cards, soldiers, wonder.</summary>
        private static List<string> Sinks(WorldState s, Ware w)
        {
            var t = s.Economy.Tuning;
            var st = s.Strategy.Tuning;
            var l = new List<string>();
            var sizes = new List<string>();
            foreach (BuildingSize size in Enum.GetValues(typeof(BuildingSize)))
                if (t.SizeCost[(int)size][(int)w] > 0) sizes.Add(size.ToString().ToLowerInvariant());
            if (sizes.Count > 0) l.Add("buildings (" + string.Join(", ", sizes) + ")");
            if (t.RoadCost[(int)w] > 0) l.Add("roads");
            if (st.CityCost[(int)w] > 0) l.Add("new cities");
            var cards = CardTable.All.Where(c => c.Cost[(int)w] > 0).Select(c => c.Name).ToList();
            if (cards.Count > 0) l.Add("cards (" + cards.Count + ": " + string.Join(", ", cards) + ")");
            if (w == Ware.Weapons && s.Military.Tuning.UnitWeapons > 0) l.Add("soldiers");
            if (w == Ware.Rations && s.Military.Tuning.UnitRations > 0) l.Add("soldiers");
            for (int i = 0; i < st.WonderStages.Length; i++) if (st.WonderStages[i][(int)w] > 0) l.Add("wonder stage " + (i + 1));
            return l;
        }

