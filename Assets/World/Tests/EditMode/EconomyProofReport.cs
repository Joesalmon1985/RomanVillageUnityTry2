        private static readonly CultureInfo Inv = CultureInfo.InvariantCulture;

        /// <summary>Breach track at the end of each random-command run (section D), for the weaknesses list.</summary>
        private static readonly List<int> RandomBreaches = new List<int>();

        private static string Min(long ticks) => (ticks / 600.0).ToString("0.0", Inv) + " min";

        private static string Sec(long ticks) => (ticks / 10.0).ToString("0.0", Inv) + " s";

        private static string Name(BuildingType t) => new EconomyTuning().Def(t).Name;

        private static string W(Ware w) => Wares.DisplayName(w);

        [Test]
        public void Proof_EconomyIsConnectedAndWorking_WritesDocsEconomyProof()
        {
            var md = new StringBuilder();
            md.Append("# Economy proof\n\n");
            md.Append("Generated by the test `EconomyProofReport` (run `dotnet test DotNet`). Every number below comes from the simulation itself; ");
            md.Append("every claim is also checked by the test, so if the economy changes and a claim stops being true, the test fails. ");
            md.Append("Time: 10 ticks = 1 second; minutes are simulated game time.\n\n");
            md.Append("Contents: A. ware audit. B. traced chains. C. cross-system links. D. conservation. E. endings. F. balance. G. known weaknesses. ");
            md.Append("The tuned numbers are listed in `Docs/ECONOMY_DESIGN.md`.\n\n");

            var weak = new List<string>();
            RandomBreaches.Clear();
            WareAudit(md);
            TracedChains(md);
            CrossLinks(md);
            Conservation(md);
            Endings(md, weak);
            Balance(md, weak);
            Weaknesses(md, weak);

            string text = md.ToString();
            string dir = FindDocs();
            if (dir != null) File.WriteAllText(Path.Combine(dir, "ECONOMY_PROOF.md"), text.Replace("\r\n", "\n"));
            TestContext.WriteLine(text);
        }

        /// <summary>The repository's Docs folder (walking up from the test folder), or null when not found.</summary>
        private static string FindDocs()
        {
            foreach (var start in new[] { TestContext.CurrentContext.TestDirectory, Directory.GetCurrentDirectory() })
            {
                var d = new DirectoryInfo(start);
                while (d != null)
                {
                    var docs = Path.Combine(d.FullName, "Docs");
                    if (File.Exists(Path.Combine(docs, "ECONOMY_DESIGN.md"))) return docs;
                    d = d.Parent;
                }
            }
            return null;
        }

