    /// <summary>
    /// The headless proof of ECONOMY_DESIGN section 9. Runs the simulation, checks every claim with an assert, and
    /// writes the plain-text report Docs/ECONOMY_PROOF.md (for a non-programmer reader). Deterministic: the same code
