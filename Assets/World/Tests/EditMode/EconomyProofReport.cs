        private sealed class Tracer
        {
            private readonly List<SimEvent> _ev;
            private readonly List<(BuildingType type, int vertex)> _b;
            public readonly List<string[]> Rows = new List<string[]>();
            public int Carries;

            public Tracer(GameRecord g)
            {
                _ev = g.Events;
                _b = g.Buildings;
            }

            public string B(int id) => Name(_b[id].type) + " (flag " + _b[id].vertex + ")";

            private T Latest<T>(Func<T, bool> ok, long before) where T : SimEvent
            {
                T best = null;
                foreach (var e in _ev)
                {
                    if (e.Tick > before) break;
                    if (e is T x && ok(x)) best = x;
                }
                return best;
            }

            private void Row(long tick, string step, string detail) => Rows.Insert(0, new[] { tick.ToString(Inv) + " (" + Min(tick) + ")", step, detail });

            /// <summary>
            /// Trace one unit of ware w that arrived at building dest at or before tick t, back to its harvest batch
            /// and the round draw. follow[type] names the recipe input to follow at each workshop.
            /// </summary>
            public bool Trace(Ware w, int dest, long t, Dictionary<BuildingType, Ware> follow)
            {
                var d = Latest<WareDelivered>(x => x.Ware == w && x.BuildingId == dest, t);
                if (d == null)
                {
                    if (_b[dest].type == BuildingType.Storehouse) { Row(0, "Start", "1 " + W(w) + " from the starting stock in the storehouse"); return true; }
                    return false;
                }
                var p = Latest<WarePickedUp>(x => x.JobId == d.JobId, d.Tick);
                if (p == null) return false;
                Carries++;
                Row(d.Tick, "Carry", "carrier " + d.CarrierId + " takes 1 " + W(w) + " from " + B(p.BuildingId) + " (picked up at tick " + p.Tick + ") to " + B(dest));
                int src = p.BuildingId;
                var type = _b[src].type;
                var def = new EconomyTuning().Def(type);
                if (type == BuildingType.Storehouse) return Trace(w, src, p.Tick, follow);
                if (def.Kind == BuildingKind.Harvester)
                {
                    var h = Latest<HarvestCycle>(x => x.BuildingId == src, p.Tick);
                    if (h == null) return false;
                    Row(h.Tick, "Harvest", B(src) + " finishes 1 batch unit on hex " + h.Hex + ": " + h.Amount + " " + W(w));
                    var ba = Latest<BatchAuthorised>(x => x.Hex == h.Hex, h.Tick);
                    if (ba == null) return false;
                    var rs = Latest<RoundStarted>(x => true, ba.Tick);
                    Row(ba.Tick, "Draw", "round " + (rs != null ? rs.Round.ToString(Inv) : "?") + " draws numbers " + (rs != null ? string.Join(", ", rs.Numbers) : "?")
                        + ": hex " + h.Hex + " gets a batch of " + ba.Amount + " " + W(ba.Ware) + " units");
                    return true;
                }
                var pc = Latest<ProductionCycle>(x => x.BuildingId == src && x.Output == w, p.Tick);
                if (pc == null) return false;
                var ps = Latest<ProductionStarted>(x => x.BuildingId == src, pc.Tick);
                if (ps == null) return false;
                Row(pc.Tick, "Recipe", B(src) + " turns " + EconomyApi.CostText(def.Inputs) + " into " + pc.Amount + " " + W(pc.Output) + " (started at tick " + ps.Tick + ")");
                if (!follow.TryGetValue(type, out var input)) return true;
                return Trace(input, src, ps.Tick, follow);
            }
        }

        private static void Table(StringBuilder md, string title, Tracer tr, string end)
        {
            md.Append("**").Append(title).Append("**\n\n| Tick (time) | Step | What happened |\n|---|---|---|\n");
            foreach (var r in tr.Rows) md.Append("| ").Append(r[0]).Append(" | ").Append(r[1]).Append(" | ").Append(r[2]).Append(" |\n");
            md.Append("\n").Append(end).Append("\n\n");
        }

        private static void TracedChains(StringBuilder md)
        {
            md.Append("## B. Traced chains\n\n");
            md.Append("Each table follows real events of one game (default seed ").Append(EconomyTestKit.DefaultSeed)
              .Append(", the scripted player that also fights) from the round's production draw to a final use. Wares are not individually labelled in the simulation, ")
              .Append("so each step is matched to the latest earlier event that could have supplied it (same ware, same building); every step really happened at the tick shown.\n\n");
            var g = GameRuns.Get(EconomyTestKit.DefaultSeed, "full", keepEvents: true);
            var ev = g.Events;
            int found = 0;

            // 1. Logs -> Planks -> wonder stage 1.
            var stage1 = ev.OfType<WonderStageCompleted>().FirstOrDefault(x => x.Stage == 1);
            Assert.IsNotNull(stage1, "wonder stage 1 completes in the traced game");
            int wonder = g.Buildings.FindIndex(b => b.type == BuildingType.WonderSite);
            var tr = new Tracer(g);
            tr.Rows.Add(new[] { stage1.Tick + " (" + Min(stage1.Tick) + ")", "Final use", "wonder stage 1 completes with the planks and bricks delivered to " + tr.B(wonder) + " (+" + stage1.Vp + " points)" });
            Assert.IsTrue(tr.Trace(Ware.Planks, wonder, stage1.Tick, new Dictionary<BuildingType, Ware> { { BuildingType.Sawmill, Ware.Logs } }), "logs chain traced");
            Table(md, "1. Logs: forest draw -> woodcutter -> sawmill -> planks -> wonder stage 1", tr, "Logs became planks and the planks became part of the wonder (" + tr.Carries + " carries).");
            found++;

            // 2. Clay -> Bricks -> a city (else a building site).
            int store = g.Buildings.FindIndex(b => b.type == BuildingType.Storehouse);
            var clayFollow = new Dictionary<BuildingType, Ware> { { BuildingType.BrickKiln, Ware.Clay } };
            tr = null;
            foreach (var city in ev.OfType<CityFounded>().Where(x => x.PlayerId == PlayerIds.Human))
            {
                var c = new Tracer(g);
                c.Rows.Add(new[] { city.Tick + " (" + Min(city.Tick) + ")", "Final use", "a city is founded on corner " + city.Vertex + ", paid from the storehouse (3 planks, 3 bricks, 2 rations): +2 points" });
                if (c.Trace(Ware.Bricks, store, city.Tick, clayFollow) && c.Rows.Any(r => r[1] == "Harvest")) { tr = c; break; }
            }
            string clayEnd = "a new city";
            if (tr == null)
            {
                clayEnd = "a building";
                foreach (var site in ev.OfType<SiteCompleted>().Where(x => new EconomyTuning().Def(x.Type).Cost[(int)Ware.Bricks] > 0))
                {
                    var c = new Tracer(g);
                    c.Rows.Add(new[] { site.Tick + " (" + Min(site.Tick) + ")", "Final use", "the " + Name(site.Type) + " is finished with the bricks delivered to its site" });
                    if (c.Trace(Ware.Bricks, site.BuildingId, site.Tick, clayFollow) && c.Rows.Any(r => r[1] == "Harvest")) { tr = c; break; }
                }
            }
            Assert.IsNotNull(tr, "clay chain traced to a harvest");
            Table(md, "2. Clay: hills draw -> clay pit -> brick kiln (with coal) -> bricks -> " + clayEnd, tr,
                "Clay became bricks (the kiln also burns one coal per two bricks) and the bricks paid for the final use (" + tr.Carries + " carries).");
            found++;

            // 3. Wheat -> Flour -> Bread -> Rations -> a mine cycle.
            var wheatFollow = new Dictionary<BuildingType, Ware> { { BuildingType.Tavern, Ware.Bread }, { BuildingType.Bakery, Ware.Flour }, { BuildingType.Mill, Ware.Wheat } };
            tr = null;
            foreach (var upkeep in ev.OfType<UpkeepPaid>())
            {
                var c = new Tracer(g);
                var ore = ev.OfType<HarvestCycle>().FirstOrDefault(h => h.BuildingId == upkeep.BuildingId && h.Tick > upkeep.Tick);
                c.Rows.Add(new[] { upkeep.Tick + " (" + Min(upkeep.Tick) + ")", "Final use", "the " + c.B(upkeep.BuildingId) + " eats 1 rations, paying for its next " + new EconomyTuning().Def(BuildingType.Mine).CyclesPerInput + " ore" + (ore != null ? " (the first of them dug at tick " + ore.Tick + ")" : "") });
                if (c.Trace(Ware.Rations, upkeep.BuildingId, upkeep.Tick, wheatFollow) && c.Rows.Any(r => r[1] == "Harvest")) { tr = c; break; }
            }
            Assert.IsNotNull(tr, "wheat chain traced");
            Table(md, "3. Wheat: fields draw -> farm -> mill -> bakery -> tavern -> rations -> a mine cycle", tr, "Wheat became flour, bread and rations, and the rations fed the miners (" + tr.Carries + " carries).");
            found++;

            // 4. Sheep -> Meat -> Rations -> a soldier.
            var sheepFollow = new Dictionary<BuildingType, Ware> { { BuildingType.Tavern, Ware.Meat }, { BuildingType.Butcher, Ware.Sheep } };
            tr = null;
            foreach (var training in ev.OfType<TrainingStarted>())
            {
                var trained = ev.OfType<UnitTrained>().FirstOrDefault(u => u.BarracksId == training.BarracksId && u.Tick > training.Tick);
                if (trained == null) continue;
                var c = new Tracer(g);
                c.Rows.Add(new[] { training.Tick + " (" + Min(training.Tick) + ")", "Final use", "the " + c.B(training.BarracksId) + " takes 1 weapons and 1 rations from its store and trains a soldier (ready at tick " + trained.Tick + ")" });
                if (c.Trace(Ware.Rations, training.BarracksId, training.Tick, sheepFollow) && c.Rows.Any(r => r[1] == "Harvest")) { tr = c; break; }
            }
            Assert.IsNotNull(tr, "sheep chain traced");
            Table(md, "4. Sheep: pasture draw -> sheepfold -> butcher -> tavern -> rations -> a soldier", tr, "Sheep became meat and rations, and the rations fed a new soldier (" + tr.Carries + " carries).");
            found++;

            // 5. Ore -> Iron -> Weapons -> soldier -> military comparison.
            var oreFollow = new Dictionary<BuildingType, Ware> { { BuildingType.Smithy, Ware.Iron }, { BuildingType.Smelter, Ware.Ore } };
            var win = g.Comparisons.FirstOrDefault(c => c.Result == ComparisonResult.Win);
            Assert.IsNotNull(win, "the traced game wins a military comparison");
            tr = null;
            foreach (var training in ev.OfType<TrainingStarted>())
            {
                var unit = ev.OfType<UnitTrained>().FirstOrDefault(u => u.BarracksId == training.BarracksId && u.Tick > training.Tick);
                if (unit == null) continue;
                var compared = ev.OfType<MilitaryCompared>().FirstOrDefault(x => x.Tick > unit.Tick);
                var c = new Tracer(g);
                if (compared != null)
                    c.Rows.Add(new[] { compared.Tick + " (" + Min(compared.Tick) + ")", "Final use", "end of Age " + StrategyApi.Roman(compared.Age) + ": shields " + compared.PlayerShields + " against the rival's " + compared.RivalShields + " -> " + compared.Result + " (" + (compared.PlayerVp >= 0 ? "+" : "") + compared.PlayerVp + " points)" });
                c.Rows.Insert(0, new[] { unit.Tick + " (" + Min(unit.Tick) + ")", "Soldier", "a soldier is trained at " + c.B(unit.BarracksId) + " and joins squad " + unit.SquadId });
                c.Rows.Insert(0, new[] { training.Tick + " (" + Min(training.Tick) + ")", "Training", "the barracks takes the delivered weapons and rations and starts training" });
                if (c.Trace(Ware.Weapons, training.BarracksId, training.Tick, oreFollow) && c.Rows.Any(r => r[1] == "Harvest")) { tr = c; break; }
            }
            Assert.IsNotNull(tr, "ore chain traced");
            Table(md, "5. Ore: mountain draw -> mine -> smelter (coal, power) -> iron -> smithy (planks) -> weapons -> soldier -> military comparison", tr,
                "Ore became iron and weapons, the weapons armed a soldier, and the soldier counted as a shield at the next age end. "
                + "In this game the first comparison won was Age " + StrategyApi.Roman(win.Age) + " (" + win.PlayerShields + " shields against " + win.RivalShields + ", +" + win.PlayerVp + " points).");
            found++;
            Assert.AreEqual(5, found);
        }

