        private static void CrossLinks(StringBuilder md)
        {
            md.Append("## C. Cross-system links\n\n");
            md.Append("Each link is shown by two runs from the same starting state that differ in one thing only (default seed, Age I started at once, fast carriers, the bell free to ring; the last two rows are paired scripted games).\n\n");
            md.Append("| Link | Run without | Run with | Result |\n|---|---|---|---|\n");

            // 1. Raw-family card: Lumber Camp makes the next forest batch larger.
            {
                var a = K.NewSim(ticksPerEdge: 60);
                var b = K.NewSim(ticksPerEdge: 60);
                K.Step(a); K.Step(b);
                K.FinishDraft(a); K.FinishDraft(b);
                K.ForceIntoHand(a.State, "lumber_camp");
                K.Do(a, new BuildCard { CardId = K.CardOf(a.State, "lumber_camp"), CityVertex = a.State.Board.HomeCityVertex });
                K.Step(b);
                int forest = EconomyTestKit.HomeHex(a.State, Terrain.Forest);
                BatchAuthorised x = null, y = null;
                for (int r = 0; r < 6 && (x == null || y == null); r++)
                {
                    x = K.EndRound(a).OfType<BatchAuthorised>().FirstOrDefault(e => e.Hex == forest);
                    y = K.EndRound(b).OfType<BatchAuthorised>().FirstOrDefault(e => e.Hex == forest);
                }
                Assert.IsNotNull(x);
                Assert.Greater(x.Amount, y.Amount);
                md.Append("| Raw card -> harvest | next forest batch ").Append(y.Amount).Append(" units | with Lumber Camp built: ").Append(x.Amount)
                  .Append(" units | the card adds 2 to the batch the draw authorises (halved here like the batch itself, because this test village has no active forester) |\n");
            }

            // 2. Demon on a city: that city's hexes stop, then resume.
            {
                long Harvest(bool demon, out int batchesNext, out int afterClear)
                {
                    var sim = K.NewSim();
                    var s = sim.State;
                    s.Strategy.Tuning.InfectionBase = 0; s.Strategy.Tuning.InfectionPerAge = 0;
                    K.Step(sim);
                    K.FinishDraft(sim);
                    int forest = EconomyTestKit.HomeHex(s, Terrain.Forest);
                    K.Build(sim, BuildingType.Woodcutter, EconomyTestKit.Touches(s, forest));
                    K.Do(sim, new MoveHero { Vertex = K.DemoCorner(s) });
                    if (demon) s.Strategy.Demons[s.Board.HomeCityVertex] = 1;
                    s.Economy.HexBatchRemaining[forest] = 8;
                    int h0 = s.Economy.Ledger.Harvested[(int)Ware.Logs];
                    K.Step(sim, 400);
                    long got = s.Economy.Ledger.Harvested[(int)Ware.Logs] - h0;
                    var evs = K.EndRound(sim);
                    batchesNext = evs.OfType<BatchAuthorised>().Count(e => s.Board.Topology.VertexHexes(s.Board.HomeCityVertex).Contains(e.Hex));
                    s.Strategy.Demons[s.Board.HomeCityVertex] = 0;
                    int h1 = s.Economy.Ledger.Harvested[(int)Ware.Logs];
                    K.Step(sim, 400);
                    afterClear = s.Economy.Ledger.Harvested[(int)Ware.Logs] - h1;
                    return got;
                }
                long without = Harvest(false, out int bWithout, out _);
                long with = Harvest(true, out int bWith, out int after);
                Assert.Greater(without, with);
                Assert.AreEqual(0, bWith);
                Assert.Greater(after, 0);
                md.Append("| Demon on a city -> production (the robber) | ").Append(without).Append(" logs felled in 40 s; ").Append(bWithout).Append(" home batches next round | demon on the home city: ")
